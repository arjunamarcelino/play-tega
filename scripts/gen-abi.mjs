#!/usr/bin/env node
// Generates web/lib/tega/abi.ts from the Foundry build artifact.
// Run after `forge build` (contracts/out is gitignored, so a fresh clone must
// build first): `cd contracts && forge build && node ../scripts/gen-abi.mjs`
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = resolve(root, "contracts/out/Tega.sol/Tega.json");
const outFile = resolve(root, "web/lib/tega/abi.ts");

const json = JSON.parse(readFileSync(artifact, "utf8"));
if (!Array.isArray(json.abi)) {
  throw new Error(`No .abi array in ${artifact} — run \`forge build\` first.`);
}

const body = `// GENERATED by scripts/gen-abi.mjs from contracts/out/Tega.sol/Tega.json — do not edit by hand.
// Regenerate after a contract interface change: cd contracts && forge build && node ../scripts/gen-abi.mjs
import type { Abi } from "viem";

export const tegaAbi = ${JSON.stringify(json.abi, null, 2)} as const satisfies Abi;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
console.log(`wrote ${outFile} (${json.abi.length} ABI entries)`);
